export function initialLanguage() {
  try {
    const saved = localStorage.getItem("trc-language");
    if (saved === "da" || saved === "en") return saved;
  } catch {
    /* Storage can be disabled. */
  }
  return navigator.language?.startsWith("da") ? "da" : "en";
}
export function translate(language, key, values = {}) {
  let text = language === "da" ? translations[key] || key : key;
  for (const [name, value] of Object.entries(values))
    text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
export const LanguageContext = createContext("en");
export function useTranslation() {
  const language = useContext(LanguageContext);
  return { language, t: (key, values) => translate(language, key, values) };
}
export function localizedWorkout(workout, language) {
  const translated = workout.translations?.[language] || {};
  const sample = workout.external_id?.startsWith("demo-");
  return Object.fromEntries(
    Object.entries(workout).map(([key, value]) => [
      key,
      ["title", "notes", "location", "pace"].includes(key)
        ? translated[key] || (sample ? translate(language, value) : value)
        : value,
    ]),
  );
}
